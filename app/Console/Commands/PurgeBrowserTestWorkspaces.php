<?php

namespace App\Console\Commands;

use App\Models\Business;
use App\Models\User;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Throwable;

final class PurgeBrowserTestWorkspaces extends Command
{
    protected $signature = 'zazu:purge-browser-test-workspaces
        {--execute : Perform the deletion; without this option the command is a dry run}
        {--confirm= : Required confirmation phrase when executing}';

    protected $description = 'Remove only synthetic Browser Catering workspaces generated by the browser registration test';

    public function handle(): int
    {
        $founderBusinessId = 24;
        $founderUserId = 27;

        if (! $this->founderWorkspaceIsValid($founderBusinessId, $founderUserId)) {
            return self::FAILURE;
        }

        $this->displayDatabaseDetails($founderBusinessId, $founderUserId);
        $businesses = $this->browserTestBusinesses();

        if ($businesses->isEmpty()) {
            return $this->noBrowserTestBusinesses();
        }

        $candidateUserIds = $this->candidateUserIds($businesses, $founderUserId);
        $this->displayCandidateBusinesses($businesses);
        $orphanedUsers = $this->orphanedUsers($candidateUserIds, $founderUserId);
        $this->displayCandidateCounts($candidateUserIds->count(), $orphanedUsers->count());

        if (! $this->option('execute')) {
            return $this->showDryRun();
        }

        if (! $this->hasExecutionConfirmation()) {
            return self::FAILURE;
        }

        return $this->purge($businesses, $candidateUserIds, $founderUserId);
    }

    private function founderWorkspaceIsValid(int $businessId, int $userId): bool
    {
        $business = Business::query()->find($businessId);
        $isFounderOwner = DB::table('business_user')
            ->where('business_id', $businessId)
            ->where('user_id', $userId)
            ->where('role', 'owner')
            ->exists();

        if (
            $business
            && $business->name === 'Rosscore Labs (Pty) Ltd'
            && $isFounderOwner
        ) {
            return true;
        }

        $this->error('Founder safety check failed. Nothing was changed.');

        return false;
    }

    private function displayDatabaseDetails(int $founderBusinessId, int $founderUserId): void
    {
        $connection = DB::connection();
        $this->line('Database connection: '.$connection->getName());
        $this->line('Database: '.$connection->getDatabaseName());
        $this->line("Protected founder workspace: #{$founderBusinessId} Rosscore Labs (Pty) Ltd; user #{$founderUserId}");
    }

    private function browserTestBusinesses()
    {
        // This exact pattern is generated by e2e/onboarding.spec.js. Do not
        // broaden it: all sensibly named businesses are intentionally preserved.
        return Business::query()
            ->with('users:id,name,email')
            ->where('name', 'like', 'Browser Catering %')
            ->orderBy('id')
            ->get()
            ->filter(fn (Business $business) =>
                preg_match('/^Browser Catering [a-f0-9]{10}$/i', (string) $business->name) === 1
            )
            ->values();
    }

    private function noBrowserTestBusinesses(): int
    {
        $this->warn('No exact Browser Catering + 10-character test workspaces found in this database.');
        $this->warn('If the browser still shows them, the running web server is using a different database/configuration or stale process.');

        return self::SUCCESS;
    }

    private function candidateUserIds($businesses, int $founderUserId)
    {
        return $businesses
            ->flatMap(fn (Business $business) => $business->users->pluck('id'))
            ->unique()
            ->reject(fn ($id) => (int) $id === $founderUserId)
            ->values();
    }

    private function displayCandidateBusinesses($businesses): void
    {
        $this->warn('ONLY THESE SYNTHETIC BROWSER-TEST WORKSPACES WILL BE REMOVED.');

        foreach ($businesses as $business) {
            $this->line(sprintf(
                'Business #%d | %s | owner/member count: %d | created: %s',
                $business->id,
                $business->name,
                $business->users->count(),
                $business->created_at?->format('Y-m-d H:i:s') ?? 'unknown'
            ));
        }
    }

    private function orphanedUsers($candidateUserIds, int $founderUserId)
    {
        return User::query()
            ->whereIn('id', $candidateUserIds)
            ->whereDoesntHave('businesses')
            ->where('id', '!=', $founderUserId)
            ->get(['id', 'name', 'email']);
    }

    private function displayCandidateCounts(int $candidateUserCount, int $orphanedUserCount): void
    {
        $this->line('Candidate linked users: '.$candidateUserCount);
        $this->line('Users that become orphaned and will be deleted: '.$orphanedUserCount);
    }

    private function showDryRun(): int
    {
        $this->comment('DRY RUN ONLY. No records changed.');
        $this->line('After confirming this is the same database used by the browser, run:');
        $this->line('php artisan zazu:purge-browser-test-workspaces --execute --confirm=DELETE-BROWSER-TEST-WORKSPACES');

        return self::SUCCESS;
    }

    private function hasExecutionConfirmation(): bool
    {
        if ($this->option('confirm') === 'DELETE-BROWSER-TEST-WORKSPACES') {
            return true;
        }

        $this->error('Execution refused: exact confirmation phrase missing. Nothing was changed.');

        return false;
    }

    private function purge($businesses, $candidateUserIds, int $founderUserId): int
    {
        try {
            [$deletedBusinesses, $deletedUsers] = DB::transaction(function () use (
                $businesses,
                $candidateUserIds,
                $founderUserId
            ): array {
                foreach ($businesses as $business) {
                    $business->delete();
                }

                $deletedUsers = User::query()
                    ->whereIn('id', $candidateUserIds)
                    ->whereDoesntHave('businesses')
                    ->where('id', '!=', $founderUserId)
                    ->delete();

                return [$businesses->count(), $deletedUsers];
            });

            $this->info("Removed {$deletedBusinesses} synthetic browser-test workspaces and {$deletedUsers} orphaned test users.");
            $this->info('All other business workspaces were left untouched.');

            return self::SUCCESS;
        } catch (Throwable $exception) {
            report($exception);
            $this->error('Purge failed; transaction rolled back. Review the application log.');

            return self::FAILURE;
        }
    }
}
